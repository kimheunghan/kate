-- =====================================================================
--  마이그레이션 020 : 보고서의 소속 기관을 선택 사항으로
--
--  소속 기관이 없는 총괄관리자(admin 같은 운영용 계정)도 보고서를
--  작성·저장할 수 있어야 한다. 다만 참여 인력이 아니므로 등록 내역과
--  기관별 집계에는 나오지 않는다.
--
--  등록 내역은 v_submission_status 를 바탕으로 만드는데, 이 뷰는
--  이미 "소속 기관이 있는 활성·승인 계정" 만 대상으로 한다(008 참고).
--  그래서 소속 없이 저장한 보고서는 저절로 목록에서 빠진다.
--
--  기존 보고서는 모두 org_id 를 갖고 있어 이 변경으로 달라지지 않는다.
--  멱등하므로 여러 번 실행해도 안전.
-- =====================================================================

SET client_encoding = 'UTF8';
SET search_path TO wr, public;

ALTER TABLE wr.reports ALTER COLUMN org_id DROP NOT NULL;

COMMENT ON COLUMN wr.reports.org_id IS
  '작성 당시 소속 기관 스냅샷 (기관별 집계용). 소속 없는 총괄관리자가 쓰면 NULL.';
